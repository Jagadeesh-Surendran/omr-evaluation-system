# ── Test 1: CNN Model ─────────────────────────────────────────────────────────

class TestCNNModel:
    """Verify BubbleCNN classifies filled/empty bubbles correctly."""

    def test_model_loads_without_error(self):
        """The model should load (or CV fallback is active)."""
        from dl_model import _load_cnn
        result = _load_cnn()  # may return True (CNN) or False (CV fallback)
        print(f"\n  CNN loaded: {result}")

    def test_filled_bubble_returns_high_probability(self):
        """Dark-filled bubble on white background → prob ≥ 0.7."""
        img = np.ones((28, 28), dtype=np.uint8) * 230
        cv2.circle(img, (14, 14), 10, 40, 2)
        cv2.circle(img, (14, 14), 8, 30, -1)
        cv2.ellipse(img, (14, 14), (7, 5), 45, 0, 360, 50, -1)
        prob = predict_bubble_dl(img)
        print(f"\n  Filled bubble probability: {prob:.4f}")
        assert prob >= 0.7, f"Expected ≥ 0.7, got {prob:.4f}"

    def test_empty_bubble_returns_low_probability(self):
        """Ring-only bubble on white background → prob < 0.3."""
        img = np.ones((28, 28), dtype=np.uint8) * 230
        cv2.circle(img, (14, 14), 10, 40, 2)
        prob = predict_bubble_dl(img)
        print(f"\n  Empty bubble probability: {prob:.4f}")
        assert prob < 0.3, f"Expected < 0.3, got {prob:.4f}"

    def test_probability_is_in_range(self):
        """Output should always be between 0.0 and 1.0."""
        for _ in range(20):
            random_img = np.random.randint(0, 255, (28, 28), dtype=np.uint8)
            prob = predict_bubble_dl(random_img)
            assert 0.0 <= prob <= 1.0, f"Probability out of range: {prob}"

    def test_handles_colour_input(self):
        """BGR colour input should not crash the model."""
        img = np.ones((28, 28, 3), dtype=np.uint8) * 200
        cv2.circle(img, (14, 14), 9, (30, 30, 30), -1)
        prob = predict_bubble_dl(img)
        assert 0.0 <= prob <= 1.0


# ── Test 2: OMR Engine ────────────────────────────────────────────────────────

class TestOMREngine:
    """Test the evaluate_omr function with the synthetic sheet."""

    def _make_answer_key(self):
        option_map = {'A': 0, 'B': 1, 'C': 2, 'D': 3, 'E': 4}
        return {q - 1: option_map[ans] for q, ans in MASTER_KEY.items()}

    def test_engine_runs_without_exception(self, test_image):
        """evaluate_omr must complete without throwing."""
        answer_key = self._make_answer_key()
        try:
            result, score = evaluate_omr(test_image, answer_key)
            print(f"\n  evaluate_omr returned: score={score}%")
        except Exception as e:
            pytest.skip(f"OMR engine could not process this image: {e}")

    def test_engine_returns_expected_score(self, test_image):
        """Score should be ≥ 40% on our synthetic sheet."""
        answer_key = self._make_answer_key()
        try:
            result, score = evaluate_omr(test_image, answer_key)
        except Exception as e:
            pytest.skip(f"OMR engine could not process this image: {e}")

        print(f"\n  Score from evaluate_omr: {score}%  (expected ~70%)")
        assert score >= 40, (
            f"Score {score}% is too low (< 40%). "
            "The model may not be detecting bubbles correctly."
        )

    def test_engine_returns_question_details(self, test_image):
        """Result must include per-question breakdown with correct keys."""
        answer_key = self._make_answer_key()
        try:
            result, score = evaluate_omr(test_image, answer_key)
        except Exception as e:
            pytest.skip(f"OMR engine could not process this image: {e}")

        print(f"\n  Question details returned: {len(result)} entries")
        assert isinstance(result, list), "question details should be a list"
        assert len(result) > 0, "question details should not be empty"

        for item in result:
            assert 'question_number' in item
            assert 'marked_answer'   in item
            assert 'correct_answer'  in item
            assert 'is_correct'      in item


# ── Test 3: Flask API Endpoint ────────────────────────────────────────────────

class TestFlaskEvaluateEndpoint:
    """Test the /api/evaluate endpoint end-to-end via HTTP."""

    def test_health_endpoint(self, client):
        """GET /api/health must return 200 with status=ok."""
        r = client.get('/api/health')
        assert r.status_code == 200
        data = json.loads(r.data)
        assert data['status'] == 'ok'
        print(f"\n  Health: {data}")

    def test_evaluate_with_real_omr_sheet(self, client):
        """POST /api/evaluate with real synthetic sheet — must return 200."""
        with open(IMG_PATH, 'rb') as img_f, open(CSV_PATH, 'rb') as csv_f:
            data = {
                'omr_files': (img_f, 'test_omr_sheet.png'),
                'answer_key_csv': (csv_f, 'answer_key.csv'),
            }
            r = client.post('/api/evaluate', data=data,
                            content_type='multipart/form-data')

        assert r.status_code == 200, f"Got {r.status_code}: {r.data.decode()}"
        result = json.loads(r.data)

        print(f"\n  /api/evaluate response keys: {list(result.keys())}")
        print(f"  Total processed : {result.get('total_processed')}")
        print(f"  Average score   : {result.get('average_score')}%")
        print(f"  Insights        : {result.get('insights', [])[:2]}")

        assert result.get('total_processed') == 1
        assert 'students'      in result
        assert 'insights'      in result
        assert 'average_score' in result
        assert len(result['insights']) > 0

    def test_evaluate_score_is_non_negative(self, client):
        """The evaluated score must always be non-negative."""
        with open(IMG_PATH, 'rb') as img_f, open(CSV_PATH, 'rb') as csv_f:
            data = {
                'omr_files': (img_f, 'test_omr_sheet.png'),
                'answer_key_csv': (csv_f, 'answer_key.csv'),
            }
            r = client.post('/api/evaluate', data=data,
                            content_type='multipart/form-data')

        result = json.loads(r.data)
        avg = result.get('average_score', 0)
        print(f"\n  Average score from API: {avg}%")
        assert avg >= 0, "Score must be non-negative"

    def test_evaluate_missing_files_returns_400(self, client):
        """No files → 400."""
        r = client.post('/api/evaluate')
        assert r.status_code == 400


# ── Test 4: Answer Key CSV Parsing ───────────────────────────────────────────

class TestCSVParsing:
    """Test that the answer key CSV is parsed correctly."""

    def test_csv_parses_all_10_questions(self):
        """CSV with 10 questions → master key has 10 entries."""
        from app import parse_answer_key_csv
        with open(CSV_PATH, 'rb') as f:
            key = parse_answer_key_csv(f)
        print(f"\n  Parsed answer key: {key}")
        assert len(key) == NUM_QUESTIONS, (
            f"Expected {NUM_QUESTIONS} entries, got {len(key)}"
        )

    def test_csv_maps_correct_options(self):
        """Q1=A should map to index 0, Q2=B→1, etc."""
        from app import parse_answer_key_csv
        option_map = {'A': 0, 'B': 1, 'C': 2, 'D': 3}
        with open(CSV_PATH, 'rb') as f:
            key = parse_answer_key_csv(f)
        for q, ans_letter in MASTER_KEY.items():
            zero_based = q - 1
            expected_idx = option_map[ans_letter]
            assert key.get(zero_based) == expected_idx, (
                f"Q{q}: expected index {expected_idx} ({ans_letter}), "
                f"got {key.get(zero_based)}"
            )

    def test_duplicate_questions_raise_error(self):
        """CSV with duplicate Q numbers should raise ValueError."""
        from app import parse_answer_key_csv
        bad_csv = io.BytesIO(b"1,A\n1,B\n2,C\n")
        with pytest.raises(ValueError, match="Duplicate"):
            parse_answer_key_csv(bad_csv)
